"""Write src/min_ands_table.hpp from min_ands_experiment.py's results.

Run with `uv run python gen/min_ands_table.py results/min_ands.json
src/min_ands_table.hpp`. Every class's count has to be a proved minimum.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main() -> None:
    """Write the table, one class per line."""
    rows = json.loads(Path(sys.argv[1]).read_text())
    unproved = [r["class"] for r in rows if not r["proved_minimum"]]
    if unproved:
        raise SystemExit(f"not proved minimal: {unproved}")
    lines = [
        "// Generated by gen/min_ands_table.py from results/min_ands.json: each",
        "// NPN class of four-view functions, by its smallest truth table, and",
        "// the fewest `and`s computing it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <utility>",
        "",
        "namespace beq {",
        "",
        f"inline constexpr std::array<std::pair<uint16_t, int>, {len(rows)}> kMinAnds{{{{",
    ]
    lines += [f"    {{0x{r['class']:04x}, {r['ands']}}}," for r in rows]
    lines += ["}};", "", "}  // namespace beq", ""]
    Path(sys.argv[2]).write_text("\n".join(lines))


if __name__ == "__main__":
    main()
